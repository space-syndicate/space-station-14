using Content.Shared.Corvax.AdminMusic;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Timing;

namespace Content.Client.Corvax.AdminMusic.UI;

/// <summary>
///     Элемент вкладки активных треков: пауза, перемотка, громкость, удаление.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AdminMusicActiveEntry : BoxContainer
{
    [Dependency] private IGameTiming _timing = default!;

    private AdminMusicTrackData? _track;

    public event Action<Guid, bool>? OnSetPaused;
    public event Action<Guid, float>? OnSeek;
    public event Action<Guid, float>? OnSetVolume;
    public event Action<Guid>? OnStop;

    public AdminMusicActiveEntry(float minVolume, float maxVolume)
    {
        RobustXamlLoader.Load(this);
        IoCManager.InjectDependencies(this);

        VolumeSlider.MinValue = minVolume;
        VolumeSlider.MaxValue = maxVolume;
        VolumeSlider.Rounded = true;
        VolumeSlider.OnValueChanged += _ => VolumeLabel.Text = AdminMusicFormat.Volume(VolumeSlider.Value);
        VolumeSlider.OnReleased += _ =>
        {
            if (_track != null)
                OnSetVolume?.Invoke(_track.Id, VolumeSlider.Value);
        };

        PositionSlider.OnValueChanged += _ =>
        {
            if (PositionSlider.Grabbed)
                UpdatePositionLabel(PositionSlider.Value);
        };
        PositionSlider.OnReleased += _ =>
        {
            if (_track != null)
                OnSeek?.Invoke(_track.Id, PositionSlider.Value);
        };

        PauseButton.OnPressed += _ =>
        {
            if (_track != null)
                OnSetPaused?.Invoke(_track.Id, _track.Status == AdminMusicTrackStatus.Playing);
        };
        StopButton.OnPressed += _ =>
        {
            if (_track != null)
                OnStop?.Invoke(_track.Id);
        };
    }

    public void UpdateTrack(AdminMusicTrackData track)
    {
        _track = track;

        TitleLabel.Text = track.Title;
        StatusLabel.Text = Loc.GetString($"admin-music-status-{track.Status.ToString().ToLowerInvariant()}");
        InfoLabel.Text = Loc.GetString("admin-music-active-info",
            ("admin", track.AdminName),
            ("listeners", track.Listeners),
            ("pending", track.Pending),
            ("failed", track.Failed),
            ("start", AdminMusicFormat.Time(track.Start)),
            ("end", AdminMusicFormat.Time(track.End)));

        var started = track.Status is AdminMusicTrackStatus.Playing or AdminMusicTrackStatus.Paused;

        PauseButton.Disabled = !started;
        PositionSlider.Disabled = !started;
        PauseButton.Text = track.Status == AdminMusicTrackStatus.Paused
            ? Loc.GetString("admin-music-active-resume")
            : Loc.GetString("admin-music-active-pause");

        PositionSlider.MinValue = 0f;
        PositionSlider.MaxValue = Math.Max(track.End, 0.1f);

        if (!VolumeSlider.Grabbed)
        {
            VolumeSlider.SetValueWithoutEvent(track.Volume);
            VolumeLabel.Text = AdminMusicFormat.Volume(track.Volume);
        }

        UpdatePosition();
    }

    protected override void FrameUpdate(FrameEventArgs args)
    {
        base.FrameUpdate(args);
        UpdatePosition();
    }

    private void UpdatePosition()
    {
        if (_track == null || PositionSlider.Grabbed)
            return;

        var position = GetPosition(_track);
        PositionSlider.SetValueWithoutEvent(position);
        UpdatePositionLabel(position);
    }

    private void UpdatePositionLabel(float position)
    {
        if (_track == null)
            return;

        PositionLabel.Text = $"{AdminMusicFormat.Time(position)} / {AdminMusicFormat.Time(_track.End)}";
    }

    private float GetPosition(AdminMusicTrackData track)
    {
        if (track.Status is not (AdminMusicTrackStatus.Playing or AdminMusicTrackStatus.Paused))
            return track.Start;

        // Так же, как сервер считает позицию у AudioComponent.
        var position = (float) ((track.PauseTime ?? _timing.CurTime) - track.AudioStart).TotalSeconds;
        return Math.Clamp(position, 0f, track.End);
    }
}
