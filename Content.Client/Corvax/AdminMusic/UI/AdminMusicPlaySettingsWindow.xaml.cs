using System.Linq;
using Content.Shared.Corvax.AdminMusic;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;
using Robust.Shared.Network;

namespace Content.Client.Corvax.AdminMusic.UI;

/// <summary>
///     Настройки воспроизведения трека: громкость, отрезок, предпрослушивание и выбор игроков.
/// </summary>
[GenerateTypedNameReferences]
public sealed partial class AdminMusicPlaySettingsWindow : DefaultWindow
{
    private const float MinFragmentLength = 0.5f;

    private readonly HashSet<NetUserId> _selectedPlayers = new();
    private List<AdminMusicPlayerData> _players = new();
    private List<AdminMusicObjectData> _objects = new();

    public AdminMusicLibraryEntry Entry { get; }

    public event Action<AdminMusicPlaySettingsWindow>? OnPreviewPressed;
    public event Action<AdminMusicPlaySettingsWindow>? OnPlayPressed;
    public event Action? OnRefreshPressed;

    public float Volume => VolumeSlider.Value;
    public float Start => StartSlider.Value;
    public float End => EndSlider.Value;
    public bool StartPaused => StartPausedCheckBox.Pressed;
    public IReadOnlyCollection<NetUserId> SelectedPlayers => _selectedPlayers;

    public AdminMusicPlaySettingsWindow(AdminMusicLibraryEntry entry, float minVolume, float maxVolume)
    {
        RobustXamlLoader.Load(this);

        Entry = entry;
        TrackLabel.Text = $"{entry.Title} [{AdminMusicFormat.Time(entry.Length)}]";

        VolumeSlider.MinValue = minVolume;
        VolumeSlider.MaxValue = maxVolume;
        VolumeSlider.Rounded = true;
        VolumeSlider.Value = Math.Clamp(0f, minVolume, maxVolume);
        VolumeSlider.OnValueChanged += _ => UpdateLabels();

        var length = Math.Max(entry.Length, MinFragmentLength);

        StartSlider.MinValue = 0f;
        StartSlider.MaxValue = length;
        StartSlider.Value = 0f;
        StartSlider.OnValueChanged += _ =>
        {
            // Начало не может быть позже конца.
            if (StartSlider.Value > EndSlider.Value - MinFragmentLength)
                StartSlider.SetValueWithoutEvent(Math.Max(0f, EndSlider.Value - MinFragmentLength));

            UpdateLabels();
        };

        EndSlider.MinValue = 0f;
        EndSlider.MaxValue = length;
        EndSlider.Value = length;
        EndSlider.OnValueChanged += _ =>
        {
            if (EndSlider.Value < StartSlider.Value + MinFragmentLength)
                EndSlider.SetValueWithoutEvent(Math.Min(length, StartSlider.Value + MinFragmentLength));

            UpdateLabels();
        };

        PreviewButton.OnPressed += _ => OnPreviewPressed?.Invoke(this);
        PlayButton.OnPressed += _ => OnPlayPressed?.Invoke(this);
        RefreshButton.OnPressed += _ => OnRefreshPressed?.Invoke();

        PlayerSearch.OnTextChanged += _ => RefreshPlayerList();
        SelectAllButton.OnPressed += _ =>
        {
            // Выбираем всех, кто виден с текущим поиском.
            foreach (var player in _players.Where(MatchesPlayerFilter))
            {
                _selectedPlayers.Add(player.UserId);
            }

            RefreshPlayerList();
        };
        ClearSelectionButton.OnPressed += _ =>
        {
            _selectedPlayers.Clear();
            RefreshPlayerList();
        };

        foreach (var type in Enum.GetValues<AdminMusicObjectType>())
        {
            ObjectTypeOptions.AddItem(Loc.GetString($"admin-music-object-type-{type.ToString().ToLowerInvariant()}"), (int) type);
        }

        ObjectTypeOptions.OnItemSelected += args =>
        {
            ObjectTypeOptions.SelectId(args.Id);
            RefreshObjectList();
        };
        ObjectSearch.OnTextChanged += _ => RefreshObjectList();
        ObjectList.OnItemSelected += args =>
        {
            if (ObjectList[args.ItemIndex].Metadata is AdminMusicObjectData obj)
                SelectPlayersOn(obj);

            ObjectList.ClearSelected();
        };

        UpdateLabels();
        RefreshPlayerList();
    }

    public void SetPreviewing(bool previewing)
    {
        PreviewButton.Text = previewing
            ? Loc.GetString("admin-music-settings-preview-stop")
            : Loc.GetString("admin-music-settings-preview");
    }

    public void SetError(string? message)
    {
        ErrorLabel.Visible = !string.IsNullOrEmpty(message);
        ErrorLabel.Text = message ?? string.Empty;
    }

    public void UpdateState(AdminMusicEuiState state)
    {
        _players = state.Players
            .OrderBy(p => p.CharacterName ?? p.Username, StringComparer.CurrentCultureIgnoreCase)
            .ToList();
        _objects = state.Objects
            .OrderBy(o => o.Name, StringComparer.CurrentCultureIgnoreCase)
            .ToList();

        // Убираем из выбора вышедших игроков.
        var online = _players.Select(p => p.UserId).ToHashSet();
        _selectedPlayers.RemoveWhere(id => !online.Contains(id));

        RefreshPlayerList();
        RefreshObjectList();
    }

    private void UpdateLabels()
    {
        VolumeLabel.Text = AdminMusicFormat.Volume(VolumeSlider.Value);
        StartLabel.Text = AdminMusicFormat.Time(StartSlider.Value);
        EndLabel.Text = AdminMusicFormat.Time(EndSlider.Value);
    }

    #region Players

    private static string GetPlayerName(AdminMusicPlayerData player)
    {
        return string.IsNullOrEmpty(player.CharacterName)
            ? player.Username
            : $"{player.CharacterName} ({player.Username})";
    }

    private bool MatchesPlayerFilter(AdminMusicPlayerData player)
    {
        var filter = PlayerSearch.Text.Trim();
        return string.IsNullOrEmpty(filter)
               || GetPlayerName(player).Contains(filter, StringComparison.CurrentCultureIgnoreCase);
    }

    private void RefreshPlayerList()
    {
        PlayerList.RemoveAllChildren();

        foreach (var player in _players)
        {
            if (!MatchesPlayerFilter(player))
                continue;

            var userId = player.UserId;
            var checkBox = new CheckBox
            {
                Text = GetPlayerName(player),
                Pressed = _selectedPlayers.Contains(userId),
            };

            checkBox.OnToggled += args =>
            {
                if (args.Pressed)
                    _selectedPlayers.Add(userId);
                else
                    _selectedPlayers.Remove(userId);

                UpdateSelected();
            };

            PlayerList.AddChild(checkBox);
        }

        UpdateSelected();
    }

    private void UpdateSelected()
    {
        SelectedLabel.Text = Loc.GetString("admin-music-settings-selected",
            ("count", _selectedPlayers.Count),
            ("total", _players.Count));

        PlayButton.Disabled = _selectedPlayers.Count == 0;
    }

    #endregion

    #region Objects

    private void RefreshObjectList()
    {
        ObjectList.Clear();

        var type = (AdminMusicObjectType) ObjectTypeOptions.SelectedId;
        var filter = ObjectSearch.Text.Trim();

        foreach (var obj in _objects)
        {
            if (obj.Type != type)
                continue;

            var text = $"{obj.Name} ({obj.Entity})";
            if (!string.IsNullOrEmpty(filter) && !text.Contains(filter, StringComparison.CurrentCultureIgnoreCase))
                continue;

            var count = _players.Count(p => IsOn(p, obj));
            ObjectList.AddItem(Loc.GetString("admin-music-settings-object-entry", ("name", text), ("count", count)),
                metadata: obj);
        }
    }

    /// <summary>
    ///     Добавляет в выбор всех игроков, находящихся на объекте.
    /// </summary>
    private void SelectPlayersOn(AdminMusicObjectData obj)
    {
        foreach (var player in _players)
        {
            if (IsOn(player, obj))
                _selectedPlayers.Add(player.UserId);
        }

        RefreshPlayerList();
    }

    private static bool IsOn(AdminMusicPlayerData player, AdminMusicObjectData obj)
    {
        return obj.Type switch
        {
            AdminMusicObjectType.Grid => player.Grid == obj.Entity,
            AdminMusicObjectType.Map => player.Map == obj.Entity,
            AdminMusicObjectType.Station => player.Station == obj.Entity,
            _ => false,
        };
    }

    #endregion
}
