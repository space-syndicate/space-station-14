using System.Linq;
using Content.Shared.Corvax.AdminMusic;
using Robust.Client.AutoGenerated;
using Robust.Client.UserInterface.Controls;
using Robust.Client.UserInterface.CustomControls;
using Robust.Client.UserInterface.XAML;

namespace Content.Client.Corvax.AdminMusic.UI;

[GenerateTypedNameReferences]
public sealed partial class AdminMusicWindow : DefaultWindow
{
    private readonly Dictionary<Guid, AdminMusicActiveEntry> _activeEntries = new();
    private IReadOnlyList<AdminMusicLibraryEntry> _library = Array.Empty<AdminMusicLibraryEntry>();
    private AdminMusicLibraryEntry? _selected;
    private float _minVolume;
    private float _maxVolume;

    public event Action? OnAddPressed;
    public event Action<AdminMusicLibraryEntry>? OnDeletePressed;
    public event Action<AdminMusicLibraryEntry>? OnSettingsPressed;
    public event Action<Guid, bool>? OnSetPaused;
    public event Action<Guid, float>? OnSeek;
    public event Action<Guid, float>? OnSetVolume;
    public event Action<Guid>? OnStop;

    public AdminMusicWindow()
    {
        RobustXamlLoader.Load(this);

        Tabs.SetTabTitle(0, Loc.GetString("admin-music-tab-library"));
        Tabs.SetTabTitle(1, Loc.GetString("admin-music-tab-active"));

        SearchBar.OnTextChanged += _ => RefreshTrackList();
        AddButton.OnPressed += _ => OnAddPressed?.Invoke();

        TrackList.OnItemSelected += args =>
        {
            _selected = TrackList[args.ItemIndex].Metadata as AdminMusicLibraryEntry;
            UpdateDetails();
        };
        TrackList.OnItemDeselected += _ =>
        {
            _selected = null;
            UpdateDetails();
        };

        SettingsButton.OnPressed += _ =>
        {
            if (_selected != null)
                OnSettingsPressed?.Invoke(_selected);
        };
        DeleteButton.OnPressed += _ =>
        {
            if (_selected != null)
                OnDeletePressed?.Invoke(_selected);
        };

        UpdateDetails();
    }

    public void SetVolumeLimits(float min, float max)
    {
        _minVolume = min;
        _maxVolume = max;
    }

    public void SetStatus(string? message)
    {
        StatusLabel.Visible = !string.IsNullOrEmpty(message);
        StatusLabel.Text = message ?? string.Empty;
    }

    #region Library

    public void SetLibrary(IReadOnlyList<AdminMusicLibraryEntry> library)
    {
        _library = library;

        if (_selected != null && !_library.Contains(_selected))
            _selected = null;

        RefreshTrackList();
    }

    private void RefreshTrackList()
    {
        var filter = SearchBar.Text.Trim();

        // Clear() снимает выделение и вызывает OnItemDeselected, поэтому сохраняем выбранный трек.
        var selected = _selected;
        TrackList.Clear();
        _selected = selected;

        foreach (var entry in _library.OrderBy(e => e.Title, StringComparer.CurrentCultureIgnoreCase))
        {
            if (!MatchesFilter(entry, filter))
                continue;

            var item = TrackList.AddItem($"{entry.Title} [{AdminMusicFormat.Time(entry.Length)}]", metadata: entry);
            item.TooltipText = entry.OriginalPath;

            if (entry == _selected)
                item.Selected = true;
        }

        UpdateDetails();
    }

    private static bool MatchesFilter(AdminMusicLibraryEntry entry, string filter)
    {
        if (string.IsNullOrEmpty(filter))
            return true;

        return entry.Title.Contains(filter, StringComparison.CurrentCultureIgnoreCase)
               || entry.TagTitle?.Contains(filter, StringComparison.CurrentCultureIgnoreCase) == true
               || entry.Artist?.Contains(filter, StringComparison.CurrentCultureIgnoreCase) == true
               || entry.OriginalPath.Contains(filter, StringComparison.CurrentCultureIgnoreCase);
    }

    private void UpdateDetails()
    {
        var entry = _selected;

        NoSelectionLabel.Visible = entry == null;
        DetailsBox.Visible = entry != null;

        if (entry == null)
            return;

        DetailsTitle.Text = entry.Title;

        var lines = new List<string>();
        if (!string.IsNullOrEmpty(entry.TagTitle) && entry.TagTitle != entry.Title)
            lines.Add(Loc.GetString("admin-music-details-tag-title", ("title", entry.TagTitle)));

        if (!string.IsNullOrEmpty(entry.Artist))
            lines.Add(Loc.GetString("admin-music-details-artist", ("artist", entry.Artist)));

        lines.Add(Loc.GetString("admin-music-details-length", ("length", AdminMusicFormat.Time(entry.Length))));
        lines.Add(Loc.GetString("admin-music-details-size", ("size", AdminMusicFormat.Size(entry.Size))));
        lines.Add(Loc.GetString("admin-music-details-added", ("added", entry.Added)));
        lines.Add(Loc.GetString("admin-music-details-path", ("path", entry.OriginalPath)));

        DetailsText.SetMessage(string.Join('\n', lines));
    }

    #endregion

    #region Active tracks

    public void ShowActiveTab()
    {
        Tabs.CurrentTab = 1;
    }

    public void UpdateActiveTracks(List<AdminMusicTrackData> tracks)
    {
        var ids = tracks.Select(t => t.Id).ToHashSet();

        foreach (var (id, entry) in _activeEntries.ToArray())
        {
            if (ids.Contains(id))
                continue;

            ActiveList.RemoveChild(entry);
            _activeEntries.Remove(id);
        }

        foreach (var track in tracks)
        {
            if (!_activeEntries.TryGetValue(track.Id, out var entry))
            {
                entry = new AdminMusicActiveEntry(_minVolume, _maxVolume);
                entry.OnSetPaused += (id, paused) => OnSetPaused?.Invoke(id, paused);
                entry.OnSeek += (id, position) => OnSeek?.Invoke(id, position);
                entry.OnSetVolume += (id, volume) => OnSetVolume?.Invoke(id, volume);
                entry.OnStop += id => OnStop?.Invoke(id);

                _activeEntries.Add(track.Id, entry);
                ActiveList.AddChild(entry);
            }

            entry.UpdateTrack(track);
        }

        NoActiveLabel.Visible = tracks.Count == 0;
        Tabs.SetTabTitle(1, tracks.Count == 0
            ? Loc.GetString("admin-music-tab-active")
            : Loc.GetString("admin-music-tab-active-count", ("count", tracks.Count)));
    }

    #endregion
}

public static class AdminMusicFormat
{
    public static string Time(float seconds)
    {
        var span = TimeSpan.FromSeconds(Math.Max(0f, seconds));
        return span.TotalHours >= 1
            ? span.ToString(@"h\:mm\:ss")
            : span.ToString(@"m\:ss");
    }

    public static string Volume(float volume)
    {
        return $"{volume:+0.#;-0.#;0} dB";
    }

    public static string Size(int bytes)
    {
        return bytes >= 1024 * 1024
            ? $"{bytes / 1024f / 1024f:F1} MB"
            : $"{bytes / 1024f:F0} KB";
    }
}
